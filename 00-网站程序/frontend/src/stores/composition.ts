1. **随机算法（RAND）**：简单，性能差
2. **先进先出（FIFO）**：先进先出，不符合局部性
3. **近期最少使用（LRU）\u2b50**：替换最久未使用的块，性能好
4. **最不经常使用（LFU）**：替换访问次数最少的

