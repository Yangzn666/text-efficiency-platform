  // 计算属性
  const currentChapter = computed(() => {
    return chapters.value.find(ch => ch.id === currentChapterId.value)
  })
  
  const currentSection = computed(() => {
    if (!currentChapter.value) return null
    const section = currentChapter.value.sections.find(sec => sec.id === currentSectionId.value)
    
    // 如果找不到匹配的小节（章节和小节不匹配），自动选择当前章节的第一个小节
    if (!section && currentChapter.value.sections.length > 0) {
      console.warn('小节ID不匹配，自动切换到章节的第一个小节')
      currentSectionId.value = currentChapter.value.sections[0].id
      return currentChapter.value.sections[0]
    }
    
    return section
  })
  
  const overallProgress = computed(() => {
    let totalSections = 0
    let studiedCount = 0
    
    chapters.value.forEach(chapter => {
      chapter.sections.forEach(section => {
        totalSections++
        if (studiedSections.value.has(section.id)) {
          studiedCount++
        }
      })
    })
    
    return totalSections > 0 ? Math.round((studiedCount / totalSections) * 100) : 0
  })
  
  // 方法
  const selectChapter = (chapterId: string) => {
    currentChapterId.value = chapterId
    const chapter = chapters.value.find(ch => ch.id === chapterId)
    if (chapter && chapter.sections.length > 0) {
      currentSectionId.value = chapter.sections[0].id
    }
  }
  
  const selectSection = (sectionId: string) => {
    currentSectionId.value = sectionId
  }
  
  const toggleSectionStudied = (sectionId: string) => {
    if (studiedSections.value.has(sectionId)) {
      studiedSections.value.delete(sectionId)
    } else {
      studiedSections.value.add(sectionId)
    }
  }
  
  const isSectionStudied = (sectionId: string) => {
    return studiedSections.value.has(sectionId)
  }
  
  return {
    // 状态
    currentChapterId,
    currentSectionId,
    studiedSections,
    chapters,
    
    // 计算属性
    currentChapter,
    currentSection,
    overallProgress,
    
    // 方法
    selectChapter,
    selectSection,
    toggleSectionStudied,
    isSectionStudied
  }
